// Generates fixtures/large: a deterministic, larger LikeC4 project for performance checks.
import { mkdirSync, writeFileSync } from 'node:fs'

const SYSTEMS = 12, CONTAINERS = 5, COMPONENTS = 4
const out = []
out.push(`specification {
  element actor { style { shape person } }
  element system
  element container
  element component
  deploymentNode environment
  deploymentNode node
}
`)
out.push('model {')
out.push(`  user = actor 'User' { description 'A user of the platform' }`)
for (let s = 1; s <= SYSTEMS; s++) {
  out.push(`  sys${s} = system 'System ${s}' {`)
  out.push(`    description 'Generated system number ${s}'`)
  for (let c = 1; c <= CONTAINERS; c++) {
    out.push(`    c${c} = container 'S${s} Container ${c}' {`)
    out.push(`      technology 'Tech ${(s + c) % 7}'`)
    for (let k = 1; k <= COMPONENTS; k++) out.push(`      k${k} = component 'S${s}C${c} Component ${k}'`)
    for (let k = 1; k < COMPONENTS; k++) out.push(`      k${k} -> k${k + 1} 'calls'`)
    out.push('    }')
  }
  for (let c = 1; c < CONTAINERS; c++) out.push(`    c${c} -> c${c + 1} 'uses'`)
  out.push('  }')
}
out.push(`  user -> sys1.c1 'uses'`)
for (let s = 1; s < SYSTEMS; s++) {
  out.push(`  sys${s}.c${CONTAINERS} -> sys${s + 1}.c1 'integrates'`)
  out.push(`  sys${s}.c2.k2 -> sys${((s + 3) % SYSTEMS) + 1}.c3.k1 'queries'`)
}
out.push('}\n')
out.push('deployment {')
out.push(`  environment prod 'Production' {`)
for (let s = 1; s <= 4; s++) {
  out.push(`    node n${s} 'Node ${s}' {`)
  for (let c = 1; c <= 3; c++) out.push(`      instanceOf sys${s}.c${c}`)
  out.push('    }')
}
out.push('  }')
out.push('}\n')
out.push('views {')
out.push(`  view index {\n    title 'Platform Landscape'\n    include *\n  }`)
for (let s = 1; s <= SYSTEMS; s++) out.push(`  view sys${s}View of sys${s} {\n    title 'System ${s}'\n    include *\n  }`)
for (let s = 1; s <= 4; s++) for (let c = 1; c <= CONTAINERS; c++) out.push(`  view s${s}c${c}View of sys${s}.c${c} {\n    include *\n  }`)
for (let s = 1; s <= 3; s++) {
  out.push(`  dynamic view flow${s} {\n    title 'Flow ${s}'`)
  out.push(`    user -> sys${s}.c1 'starts'`)
  for (let c = 1; c < CONTAINERS; c++) out.push(`    sys${s}.c${c} -> sys${s}.c${c + 1} 'step ${c}'`)
  out.push('  }')
}
out.push(`  deployment view prodView {\n    title 'Production'\n    include prod.**\n  }`)
out.push('}')

mkdirSync('fixtures/large/docs', { recursive: true })
writeFileSync('fixtures/large/likec4.config.json', JSON.stringify({ $schema: 'https://likec4.dev/schemas/config.json', name: 'large' }, null, 2) + '\n')
writeFileSync('fixtures/large/model.c4', out.join('\n') + '\n')
const views = ['index', 'sys1View', 'sys2View', 'sys3View', 's1c1View', 's1c2View', 'flow1', 'flow2', 'prodView', 'sys4View']
writeFileSync('fixtures/large/docs/architecture.md', `# Large model (10 views)\n\nGenerated by scripts/gen-large-fixture.mjs.\n\n${views.map((v, i) => `## ${i + 1}. ${v}\n\n\`\`\`likec4-view\n${v}\n\`\`\`\n`).join('\n')}`)
console.log('views', 1 + SYSTEMS + 4 * CONTAINERS + 3 + 1, 'elements', 1 + SYSTEMS * (1 + CONTAINERS * (1 + COMPONENTS)))
