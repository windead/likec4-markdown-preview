// Generates THIRD_PARTY_NOTICES from the packages bundled into dist/ (esbuild metafile).
import { execSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const meta = JSON.parse(readFileSync('dist/meta.json', 'utf8'))
const dirs = new Set()
for (const build of Object.values(meta)) {
  for (const out of Object.values(build.outputs)) {
    for (const input of Object.keys(out.inputs)) {
      // innermost node_modules package (handles nested node_modules)
      const m = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//)
      if (m) dirs.add(m[1])
    }
  }
}

const LICENSE_FILES = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i
const entries = []
for (const dir of [...dirs].sort()) {
  if (!existsSync(join(dir, 'package.json'))) {
    // code vendored inside another package's dist (pnpm layout): .pnpm/<name@version_peer>/node_modules/<name>
    const m = dir.match(/^node_modules\/(.+?)\/dist\/node_modules\/\.pnpm\/([^/]+)\/node_modules\/((?:@[^/]+\/)?[^/]+)$/)
    if (!m) throw new Error(`cannot identify bundled package at ${dir}`)
    const [, parent, seg, name] = m
    const version = (seg.match(/@(\d+\.\d+\.\d+[^_]*)/) ?? [])[1] ?? 'unknown'
    let license = 'UNKNOWN'
    try {
      license = execSync(`npm view ${name}@${version} license`, { encoding: 'utf8', timeout: 60000 }).trim() || license
    } catch {}
    entries.push({ name, version, license, repo: `https://www.npmjs.com/package/${name}`, texts: [`Vendored (pre-bundled) inside ${parent}. Licensed under ${license}; see the package's LICENSE at ${name}@${version}.`] })
    continue
  }
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const license = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses ?? []).map(l => l.type).join(' OR ') ?? 'UNKNOWN'
  const repo = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? pkg.homepage ?? ''
  const texts = readdirSync(dir).filter(f => LICENSE_FILES.test(f)).map(f => readFileSync(join(dir, f), 'utf8').trim())
  const inferred = license || (/MIT License/i.test(texts[0] ?? '') ? 'MIT' : /Apache License/i.test(texts[0] ?? '') ? 'Apache-2.0' : /ISC License/i.test(texts[0] ?? '') ? 'ISC' : 'UNKNOWN')
  entries.push({ name: pkg.name, version: pkg.version, license: inferred, repo, texts })
}
// de-duplicate same name@version
const seen = new Set()
const unique = entries.filter(e => (seen.has(`${e.name}@${e.version}`) ? false : seen.add(`${e.name}@${e.version}`)))

// Components compiled into @hpcc-js/wasm-graphviz (WebAssembly build of Graphviz)
const extra = [
  {
    name: 'Graphviz (compiled into @hpcc-js/wasm-graphviz)',
    version: 'see @hpcc-js/wasm-graphviz ' + (unique.find(e => e.name === '@hpcc-js/wasm-graphviz')?.version ?? ''),
    license: 'EPL-1.0',
    repo: 'https://gitlab.com/graphviz/graphviz',
    texts: ['Graphviz is licensed under the Eclipse Public License, Version 1.0.\nFull license text: https://www.eclipse.org/legal/epl-v10.html\nSource code: https://gitlab.com/graphviz/graphviz'],
  },
  {
    name: 'Expat (compiled into @hpcc-js/wasm-graphviz)',
    version: '',
    license: 'MIT',
    repo: 'https://github.com/libexpat/libexpat',
    texts: ['Copyright (c) 1998-2000 Thai Open Source Software Center Ltd and Clark Cooper\nCopyright (c) 2001-2025 Expat maintainers\n\nPermission is hereby granted, free of charge, to any person obtaining a copy of this software and associated documentation files (the "Software"), to deal in the Software without restriction, including without limitation the rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the Software, and to permit persons to whom the Software is furnished to do so, subject to the following conditions:\n\nThe above copyright notice and this permission notice shall be included in all copies or substantial portions of the Software.\n\nTHE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE.'],
  },
]

const missing = unique.filter(e => e.texts.length === 0).map(e => `${e.name}@${e.version} (${e.license})`)
const lines = [
  'THIRD-PARTY SOFTWARE NOTICES',
  '',
  'Markdown Preview for LikeC4 bundles the following third-party software in dist/extension.js and dist/preview.js.',
  'This file is generated by scripts/notices.mjs from the esbuild metafile; do not edit by hand.',
  '',
  'Summary:',
  ...[...unique, ...extra].map(e => `- ${e.name}${e.version ? ` ${e.version}` : ''} — ${e.license}`),
  '',
]
for (const e of [...unique, ...extra]) {
  lines.push('='.repeat(80), `${e.name}${e.version ? ` ${e.version}` : ''}`, `License: ${e.license}`)
  if (e.repo) lines.push(`Source: ${e.repo}`)
  lines.push('-'.repeat(80))
  lines.push(e.texts.length ? e.texts.join('\n\n' + '-'.repeat(40) + '\n\n') : `(No license file shipped in the package; licensed under ${e.license} per its package.json.)`)
  lines.push('')
}
writeFileSync('THIRD_PARTY_NOTICES', lines.join('\n'))
console.log(`THIRD_PARTY_NOTICES: ${unique.length} packages + ${extra.length} embedded components; without license file: ${missing.length}`)
if (missing.length) console.log('  ' + missing.join('\n  '))
const licenses = {}
for (const e of unique) licenses[e.license] = (licenses[e.license] ?? 0) + 1
console.log('licenses:', JSON.stringify(licenses))
